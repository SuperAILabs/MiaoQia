"""三语言代码生成。生成物提交到仓库；`--check` 在临时目录重新生成并与已提交文件逐字节比较。

  Go          services/contracts/contracts_gen.go       go-jsonschema（版本固定于 tools/contracts/gotools/go.mod）
  Python      data/contracts/src/miaoqia/contracts/models.py   datamodel-code-generator（版本固定于 tools/contracts/pyproject.toml）
  TypeScript  web/packages/contracts/src/index.ts        json-schema-to-typescript（版本固定于 web/packages/contracts/package.json）

子系统接口（contracts/apis/<子系统>/openapi.yaml）：
  Go          services/contracts/apis/<子系统>/          ogen 生成客户端与服务端（包名 <子系统>api，版本固定于 gotools/go.mod）

pnpm 命令可用环境变量 MQC_PNPM 覆盖（例如 "npx -y pnpm@9.15.9"）。
"""
from __future__ import annotations

import json
import os
import re
import shlex
import subprocess
import sys
import tempfile
from pathlib import Path

from .bundle import build_bundle
from .repo import Repo
from .report import Report

HEADER = "由 tools/contracts（mqc generate）从 contracts/schemas 生成，请勿手改。"
ROOT_TYPE = "MiaoQiaContracts"

TARGETS = {
    "go": Path("services/contracts/contracts_gen.go"),
    "python": Path("data/contracts/src/miaoqia/contracts/models.py"),
    "typescript": Path("web/packages/contracts/src/index.ts"),
}


def _run(cmd: list[str], cwd: Path) -> None:
    res = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if res.returncode != 0:
        raise RuntimeError(f"命令失败（{cwd}）：{' '.join(cmd)}\n{res.stdout}\n{res.stderr}")


def _gen_go(repo: Repo, bundle: Path, out: Path) -> None:
    _run(["go", "tool", "go-jsonschema", "--only-models", "--tags", "json", "-p", "contracts",
          str(bundle), "-o", str(out)], repo.root / "tools/contracts/gotools")
    text = out.read_text(encoding="utf-8")
    text = text.replace("// Code generated by github.com/atombender/go-jsonschema, DO NOT EDIT.",
                        f"// Code generated by github.com/atombender/go-jsonschema, DO NOT EDIT.\n// {HEADER}", 1)
    out.write_text(text, encoding="utf-8")
    _run(["gofmt", "-w", str(out)], repo.root)


def _quote_self_ref(m: re.Match) -> str:
    name, args = m[1], m[2]
    args = re.sub(r"\b" + name + r"\b", '"' + name + '"', args)
    return f"class {name}(RootModel[{args}]):"


def _gen_python(repo: Repo, bundle: Path, out: Path) -> None:
    _run([sys.executable, "-m", "datamodel_code_generator",
          "--input", str(bundle), "--input-file-type", "jsonschema",
          "--output-model-type", "pydantic_v2.BaseModel", "--target-python-version", "3.12",
          "--use-standard-collections", "--use-union-operator", "--use-double-quotes",
          "--disable-timestamp", "--custom-file-header", f"# {HEADER}", "--output", str(out)], repo.root)
    text = out.read_text(encoding="utf-8")
    # 去掉打包根节点产生的占位模型
    text = re.sub(rf"\n\nclass {ROOT_TYPE}\(RootModel\[Any\]\):\n(?:    .*\n)+", "\n", text)
    # 递归的根模型（如 RecordValue）在基类泛型参数中引用自身，类定义时尚不存在：改为前向引用，由文件末尾的 model_rebuild 解析
    text = re.sub(r"^class (\w+)\(RootModel\[(.*)\]\):$", _quote_self_ref, text, flags=re.M)
    out.write_text(text, encoding="utf-8")


def _gen_typescript(repo: Repo, bundle: Path, out: Path) -> None:
    pnpm = shlex.split(os.environ.get("MQC_PNPM", "pnpm"))
    _run(pnpm + ["exec", "json2ts", "-i", str(bundle), "-o", str(out), "--unreachableDefinitions",
                 "--bannerComment", f"/* {HEADER} */"], repo.root / "web/packages/contracts")
    text = out.read_text(encoding="utf-8")
    # 去掉打包根节点产生的注释行
    text = re.sub(rf" \*\n \* This interface was referenced by `{ROOT_TYPE}`'s JSON-Schema\n \* via the `definition` \"[A-Za-z0-9]+\"\.\n", "", text)
    text = re.sub(rf" \* This interface was referenced by `{ROOT_TYPE}`'s JSON-Schema\n \* via the `definition` \"[A-Za-z0-9]+\"\.\n", "", text)
    text = re.sub(rf"/\*\*\n \* 生成用打包 Schema\n \*/\nexport interface {ROOT_TYPE} \{{\n  \[k: string\]: unknown;\n\}}\n", "", text)
    text = text.replace("/**\n */\n", "")
    out.write_text(text, encoding="utf-8")


GENERATORS = {"go": _gen_go, "python": _gen_python, "typescript": _gen_typescript}


def _gen_apis(repo: Repo, tmpd: Path, check: bool, r: Report) -> int:
    specs = sorted((repo.contracts / "apis").glob("*/openapi.yaml"))
    for spec in specs:
        sub = spec.parent.name
        rel = Path("services/contracts/apis") / sub
        out = tmpd / "apis" / sub
        _run(["go", "tool", "ogen", "-clean", "-package", sub.replace("-", "") + "api", "-target", str(out), str(spec)],
             repo.root / "tools/contracts/gotools")
        new = {f.name: f.read_bytes() for f in sorted(out.glob("*.go"))}
        target = repo.root / rel
        if check:
            old = {f.name: f.read_bytes() for f in sorted(target.glob("*.go"))} if target.exists() else {}
            if old != new:
                r.error(str(rel), "接口生成物与 OpenAPI 不一致，请运行 mqc generate 并提交")
        else:
            target.mkdir(parents=True, exist_ok=True)
            for f in target.glob("*.go"):
                f.unlink()
            for name, b in new.items():
                (target / name).write_bytes(b)
            r.note(f"已生成 {rel}/")
    return len(specs)


def generate(repo: Repo, check: bool, langs: list[str]) -> Report:
    r = Report()
    # 运行时载荷复用与兼容检查相同的引用展开，保留全部校验关键字。
    from .compat import _messages
    from .repo import load_yaml
    from .fixtures import _apply
    import copy
    runtime_cases = []
    for path in sorted((repo.contracts / "events").glob("*/fixtures.yaml")):
        for spec in load_yaml(path).get("fixtures", []):
            for case in [{"name":"base", "valid":True}, *spec.get("cases", [])]:
                value = copy.deepcopy(case.get("instance", spec["base"]))
                for patch in case.get("patch", []):
                    value = _apply(value, patch)
                runtime_cases.append({"event":spec["event"], "name":case["name"], "valid":case["valid"], "value":value})
    runtime_bytes = (json.dumps({"schemas": _messages(repo), "cases":runtime_cases}, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode()
    for rel in [Path("services/contracts/events/payloads.json"), Path("data/contracts/src/miaoqia/contracts/event_payloads.json")]:
        path = repo.root / rel
        if check:
            if not path.exists() or path.read_bytes() != runtime_bytes:
                r.error(str(rel), "运行时载荷制品与AsyncAPI不一致")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(runtime_bytes)
    bundle = build_bundle(repo)
    with tempfile.TemporaryDirectory() as tmp:
        tmpd = Path(tmp)
        bpath = tmpd / "contracts.bundle.json"
        bpath.write_text(json.dumps(bundle, ensure_ascii=False, indent=2), encoding="utf-8")
        for lang in langs:
            target = repo.root / TARGETS[lang]
            out = tmpd / target.name
            GENERATORS[lang](repo, bpath, out)
            new = out.read_bytes()
            if check:
                if not target.exists() or target.read_bytes() != new:
                    r.error(str(TARGETS[lang]), "生成物与契约不一致，请运行 mqc generate 并提交")
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(new)
                r.note(f"已生成 {TARGETS[lang]}")
        n_api = _gen_apis(repo, tmpd, check, r) if "go" in langs else 0
    r.note(f"代码生成{'一致性检查' if check else ''}：{len(bundle['$defs'])} 个类型 × {len(langs)} 种语言；{n_api} 个子系统接口")
    return r
