-- 在公开数据面专用的新集群中从 postgres 数据库执行一次，启用 ON_ERROR_STOP。
-- 由凭据所有者另行建立角色登录凭据。公共检索库使用其独立的引导文件。

\set ON_ERROR_STOP on
DO $$
BEGIN
    IF current_database() <> 'postgres' OR EXISTS (
        SELECT 1 FROM pg_database WHERE datname NOT IN ('postgres', 'template0', 'template1')
    ) THEN
        RAISE EXCEPTION 'public data bootstrap requires a new dedicated PostgreSQL cluster';
    END IF;
END $$;

REVOKE CONNECT ON DATABASE postgres, template1 FROM PUBLIC;
CREATE ROLE outbox_relay NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;

-- acquisition（Python，acquisition）
CREATE ROLE acq_owner NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
CREATE ROLE acq_app NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
CREATE DATABASE acq OWNER acq_owner;
REVOKE ALL ON DATABASE acq FROM PUBLIC;
GRANT CONNECT ON DATABASE acq TO acq_app, outbox_relay;
\connect acq
ALTER SCHEMA public OWNER TO acq_owner;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO acq_app;
ALTER DEFAULT PRIVILEGES FOR ROLE acq_owner IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO acq_app;
ALTER DEFAULT PRIVILEGES FOR ROLE acq_owner IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO acq_app;
\connect postgres

